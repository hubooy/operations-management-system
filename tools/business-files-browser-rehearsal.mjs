import assert from "node:assert/strict";
import fs from "node:fs/promises";
import path from "node:path";
import { pathToFileURL } from "node:url";
import { chromium } from "playwright-core";

const directory = path.resolve(process.argv[2] ?? "");
const manifest = JSON.parse(await fs.readFile(path.join(directory, "manifest.json"), "utf8"));
const expectedRows = manifest.tables.find(t => t.key === "raw").rowCount;
const browser = await chromium.launch({ headless: true, executablePath: "C:\\Program Files\\Google\\Chrome\\Application\\chrome.exe" });
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 }, acceptDownloads: true });
const errors = [], requests = [];
page.on("pageerror", error => errors.push(String(error)));
page.on("request", request => { if (/^https?:/.test(request.url())) requests.push(request.url()); });
try {
  await page.goto(pathToFileURL(path.join(directory, "report.html")).href);
  await page.locator("#tbody tr").first().waitFor();
  assert.equal(await page.locator("#tbody tr").count(), 3);
  assert.equal(await page.locator("#tbody tr").first().locator("td").nth(3).textContent(), "5.00%");
  await page.locator("details").first().locator("summary").click();
  await page.locator("#chart-column").selectOption("1");
  assert.equal(await page.locator("#chart rect").count(), 2);
  await page.screenshot({ path: path.join(directory, "html-overview.png"), fullPage: true });
  await page.locator("#nav button").nth(1).click();
  assert.equal(await page.locator("#tbody tr").count(), 100);
  await page.locator("#next").click();
  assert.equal(await page.locator("#tbody tr").first().locator("td").first().textContent(), "词000100");
  await page.locator("#search").fill(`词${String(expectedRows-1).padStart(6, "0")}`);
  assert.equal(await page.locator("#tbody tr").count(), 1);
  await page.locator("#search").fill("");
  await page.locator("#missing").selectOption("missing");
  assert.match(await page.locator("#count").textContent(), new RegExp(String(Math.ceil(expectedRows/7)).replace(/\B(?=(\d{3})+(?!\d))/g, ",")));
  await page.locator("#missing").selectOption("complete");
  await page.locator("#sort").selectOption("2");
  await page.locator("#order").click();
  assert.equal(await page.locator("#tbody tr").first().locator("td").nth(2).textContent(), "9");
  await page.locator("#nav button").nth(2).click();
  assert.equal(await page.evaluate(() => window.attacked), undefined);
  assert.equal(await page.locator("#tbody script").count(), 0);
  const downloaded = page.waitForEvent("download");
  await page.locator("#export").click();
  const download = await downloaded;
  const csvPath = path.join(directory, "literal.csv");
  await download.saveAs(csvPath);
  const csv = await fs.readFile(csvPath, "utf8");
  assert.ok(csv.includes("'=1+1"));
  assert.ok(csv.includes("9999999999999999"));
  await page.setViewportSize({ width: 390, height: 844 });
  await page.locator("#nav button").first().click();
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
  await page.screenshot({ path: path.join(directory, "html-mobile.png"), fullPage: true });
  assert.deepEqual(errors, []);
  assert.deepEqual(requests, []);
  const result = { passed: true, expectedRows, searchBeyondFirstPage: true, pagination: true, sort: true, missingFilter: true, svgChart: true, csvLiteralSafety: true, mobileLayout: true, externalRequests: requests.length, errors };
  await fs.writeFile(path.join(directory, "browser-evidence.json"), JSON.stringify(result, null, 2));
  console.log(JSON.stringify(result));
} finally {
  await browser.close();
}
